use browser_profile::UiLanguage;

pub fn t(lang: UiLanguage, key: &str) -> &'static str {
    let value = match lang {
        UiLanguage::Russian => ru(key),
        UiLanguage::Ukrainian => uk(key),
        UiLanguage::German => de(key),
        UiLanguage::Spanish => es(key),
        UiLanguage::French => fr(key),
        UiLanguage::Chinese => zh(key),
        UiLanguage::English => en(key),
    };
    if value == "???" {
        en(key)
    } else {
        value
    }
}

